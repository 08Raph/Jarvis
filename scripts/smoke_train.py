"""End-to-end smoke test on a machine WITH PyTorch:  python scripts/smoke_train.py

Checks: data pipeline -> tokenizer -> from-scratch GPT training -> interrupt and
resume -> best-checkpoint test evaluation -> generation -> gated answer.
Uses a synthetic, project-original corpus. It proves the pipeline runs; the
resulting model is a toy and will NOT give useful answers.
"""
import json
import random
import string
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from jarvis.data.pipeline import prepare_dataset
from jarvis.data.provenance import ProvenanceLedger
from jarvis.inference.engine import InferenceEngine
from jarvis.inference.policy import AnswerGate
from jarvis.train.pretrain import TrainConfig, run

rng = random.Random(0)
vocab = ["".join(rng.choice(string.ascii_lowercase) for _ in range(rng.randint(3, 7))) for _ in range(60)]
paras = [" ".join(rng.choice(vocab) for _ in range(40)) + "." for _ in range(400)]

with tempfile.TemporaryDirectory() as d:
    d = Path(d)
    (d / "corpus.txt").write_text("\n\n".join(paras), encoding="utf-8")
    led = ProvenanceLedger(d / "ledger.sqlite")
    led.register(d / "corpus.txt", "synthetic", "generated by smoke script", "project-original")
    led.close()
    rep = prepare_dataset(d / "ledger.sqlite", d / "data", seed=1, val_frac=0.1, test_frac=0.1, ngram=8)
    print("dataset stages:", rep["stages"], "warnings:", rep["warnings"])

    base = dict(data_dir=str(d / "data"), out_dir=str(d / "model"), vocab_size=300, block_size=32,
                n_layer=2, n_head=2, n_embd=64, batch_size=8, eval_interval=10, ckpt_interval=10,
                eval_iters=5, warmup_steps=5, patience=100, seed=1)
    run(TrainConfig(max_steps=20, **base))                       # "interrupted" at step 20
    m = run(TrainConfig(max_steps=40, resume=True, **base))      # resume to 40
    steps = [h["step"] for h in m["history"]]
    assert steps == [10, 20, 30, 40], f"resume history broken: {steps}"
    assert m["history"][-1]["train_loss"] < m["history"][0]["train_loss"] + 1.0, "training diverged"
    print("test_loss:", m["test_loss"], "params:", m["params"])

    eng = InferenceEngine(d / "model")
    text, lp = eng.generate_scored("hello", max_new_tokens=20)
    print("sample:", repr(text), "mean_logprob:", round(lp, 2))
    print("gate:", AnswerGate().decide(text, lp))
    print("SMOKE TEST PASSED")
